"""Draws every pet in web/pets.json as pixel art for the Claude Code add-on: claude-code/hooks/sprites.ts.

Each pet is drawn in headless Chrome at 112x64 (cropped to its art, standing on the bottom edge), shrunk to
28x16 pixels taking each 4x4 block's most common color so edges stay crisp, and written as a palette plus rows
of palette letters. The terminal shows two pixel rows per cell (▀ over ▄): 28 columns by 8 lines.
Run: python3 tools/claude_sprites.py   (CHROME=/path/to/chrome to choose the browser; needs Pillow)
"""
import glob, json, os, pathlib, subprocess, tempfile
from collections import Counter
from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA = json.loads((ROOT / "web/pets.json").read_text())
W, H, BLOCK = 112, 64, 4
COLS, ROWS = W // BLOCK, H // BLOCK
KEYS = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789"


def chrome():
    if os.environ.get("CHROME"):
        return os.environ["CHROME"]
    for path in ["/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
                 *sorted(glob.glob(os.path.expanduser("~/Library/Caches/ms-playwright/chromium-*/chrome-mac*/*.app/Contents/MacOS/*")), reverse=True)]:
        if os.path.exists(path):
            return path
    raise SystemExit("No Chrome found; set CHROME.")


def sheet(path):
    """Every pet, one under another, eyes open, on a transparent background."""
    page = f"""<!doctype html><html><head><meta charset="utf-8"><style>
html, body {{ margin: 0; background: transparent; }} svg {{ display: block; width: {W}px; height: {H}px; }}
</style></head><body><div id="all"></div><script>
const DATA = {json.dumps(DATA)}, NS = "http://www.w3.org/2000/svg";
function shape(part) {{
  let el;
  if (part.path) {{ el = document.createElementNS(NS, "path"); el.setAttribute("d", part.path); }}
  else if (part.circle) {{ el = document.createElementNS(NS, "circle"); const [cx, cy, r] = part.circle; el.setAttribute("cx", cx); el.setAttribute("cy", cy); el.setAttribute("r", r); }}
  else {{ el = document.createElementNS(NS, "ellipse"); const [cx, cy, rx, ry] = part.ellipse; el.setAttribute("cx", cx); el.setAttribute("cy", cy); el.setAttribute("rx", rx); el.setAttribute("ry", ry); }}
  el.setAttribute("fill", part.fill || "none");
  // Lines a little heavier than in the editors, so they survive the shrink.
  if (part.stroke) {{ el.setAttribute("stroke", part.stroke); el.setAttribute("stroke-width", (part.sw || 1) * 1.6); el.setAttribute("stroke-linecap", "round"); el.setAttribute("stroke-linejoin", "round"); }}
  if (part.opacity != null) el.setAttribute("opacity", part.opacity);
  return el;
}}
for (const id of DATA.order) {{
  const svg = document.createElementNS(NS, "svg"), g = document.createElementNS(NS, "g");
  for (const part of DATA.pets[id].parts) if (!part.when || part.when.includes("eyesOpen")) g.appendChild(shape(part));
  svg.appendChild(g); document.getElementById("all").appendChild(svg);
  const b = g.getBBox(), pad = 6, scale = Math.min({W} / (b.width + pad * 2), {H} / (b.height + pad * 2));
  const vw = {W} / scale, vh = {H} / scale;
  svg.setAttribute("viewBox", `${{b.x + b.width / 2 - vw / 2}} ${{b.y + b.height + pad - vh}} ${{vw}} ${{vh}}`);
}}
</script></body></html>"""
    with tempfile.NamedTemporaryFile("w", suffix=".html", delete=False) as f:
        f.write(page)
    subprocess.run([chrome(), "--headless", "--hide-scrollbars", "--force-device-scale-factor=1", "--default-background-color=00000000",
                    f"--window-size={W},{H * len(DATA['order'])}", "--virtual-time-budget=1500", f"--screenshot={path}", f"file://{f.name}"],
                   check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    os.unlink(f.name)


def shrink(image, index):
    quant = lambda c: tuple(min(255, round(v / 8) * 8) for v in c[:3])
    pixels = []
    for y in range(ROWS):
        row = []
        for x in range(COLS):
            block = [image.getpixel((x * BLOCK + dx, index * H + y * BLOCK + dy)) for dy in range(BLOCK) for dx in range(BLOCK)]
            solid = [p for p in block if p[3] > 140]
            row.append(Counter(quant(p) for p in solid).most_common(1)[0][0] if len(solid) >= 6 else None)
        pixels.append(row)
    palette = sorted({c for row in pixels for c in row if c})
    keys = {c: KEYS[n] for n, c in enumerate(palette)}
    return ["#%02x%02x%02x" % c for c in palette], ["".join(keys[c] if c else "." for c in row) for row in pixels]


with tempfile.TemporaryDirectory() as tmp:
    png = os.path.join(tmp, "sheet.png")
    sheet(png)
    image = Image.open(png).convert("RGBA")
    out = ["// Generated by tools/claude_sprites.py from web/pets.json: each pet as 28x16 pixels, two to a terminal cell (▀ ▄).",
           "// \".\" is empty; each other letter indexes the pet's palette. flip: the art faces right and turns to walk left.",
           "export type Sprite = { palette: string[]; rows: string[]; flip: boolean }", "",
           "export const SPRITES: Record<string, Sprite> = {"]
    for i, pet in enumerate(DATA["order"]):
        palette, rows = shrink(image, i)
        out.append(f"  {pet}: {{ flip: {'true' if DATA['pets'][pet]['flip'] else 'false'}, palette: {json.dumps(palette)}, rows: [")
        out += [f"    {json.dumps(r)}," for r in rows]
        out.append("  ] },")
    out.append("}")
    (ROOT / "claude-code/hooks/sprites.ts").write_text("\n".join(out) + "\n")
print(ROOT / "claude-code/hooks/sprites.ts")
